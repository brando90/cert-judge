#!/usr/bin/env python3
"""TLDR: Render experiment 42's machine-readable results (results/semantic_screen.json and, when present,
results/index_association.json) as Markdown tables in results/RESULTS_semantic_screen.md for REPORT.md and
results.md. Zero model calls."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parent)]
import e42                                                    # noqa: E402

ORDER = list(e42.MODELS) + ["ctl"]


def f(x, nd: int = 2) -> str:
    return "—" if x is None else f"{x:.{nd}f}"


def ci(m: dict, nd: int = 2) -> str:
    if m.get("value") is None:
        return "—"
    return f"{m['value']:.{nd}f} [{f(m['lo'], nd)}, {f(m['hi'], nd)}]"


def main() -> int:
    screen = e42.read_json(e42.RESULTS / "semantic_screen.json")
    units = sorted(screen["units"], key=lambda u: (ORDER.index(u["config"].split("|")[0]) if u["config"].split("|")[0] in ORDER else 99, u["config"]))
    lines = ["# Experiment 42 semantic screen tables", "",
             "**TLDR:** Per-configuration directional accuracy (vacuity, weakening, over-constraint), Kendall τ with weakening level, "
             "formatting gap and the locked pass rule, with task-clustered 95% bootstrap intervals; generated by `scripts/report_tables.py`.", "",
             f"Rule: {screen['rule']}. Verdicts: {screen['verdicts']}. Total Vals-reported charges over merged configurations: ${screen['total_charges_usd']:.2f}.", "",
             "| Configuration | Split (exp. 39) | DA vacuity | DA weakening | DA over-constraint | τ (weak. level) | Formatting gap | Identity mean | Verdict | Fmt false alarm | Discrimination | Strict-only DA weak. / over. | Charges $ |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for u in units:
        m = u["metrics"]
        strict = m.get("file_level_strict_only") or {}
        lines.append(f"| `{u['config']}` | {u.get('split') or '—'} | {ci(m['vacuity'])} | {ci(m['weakening'])} | {ci(m['overconstraint'])} | "
                     f"{ci(m['weakening_kendall_tau'])} | {ci(m['formatting'], 3)} | {f(m.get('identity_mean_score'))} | {u['verdict']} | {ci(m.get('formatting_false_alarm') or {})} | {f(m.get('discrimination'))} | "
                     f"{f((strict.get('weakening') or {}).get('value'))} / {f((strict.get('overconstraint') or {}).get('value'))} | {f(u.get('charges_usd'))} |")
    idx_path = e42.RESULTS / "index_association.json"
    if idx_path.exists():
        idx = e42.read_json(idx_path)
        lines += ["", f"## Association with experiment 39's criterion ({idx['criterion']}; ref {idx['e39_ref']} = {idx['e39_ref_commit'][:10]}; test view: {idx['test_view']})", ""]
        for view, block in idx["views"].items():
            lines += [f"### {view} ({block['n_units']} LLM units)", "", "| Component | Spearman | 95% CI | Kendall | one-sided perm p | n |", "|---|---|---|---|---|---|"]
            for name, a in block["components"].items():
                lines.append(f"| {name} | {f(a['spearman'])} | [{f(a['ci95']['lo'])}, {f(a['ci95']['hi'])}] | {f(a['kendall'])} | {f(a['perm_p_one_sided'], 4)} | {a['n']} |")
            aug = [(k, v) for k, v in block.items() if k.startswith("augmented_")]
            if aug:
                lines += ["", "| Base index | Spearman base | Spearman GM(base, S) | Δ | Δ 95% CI |", "|---|---|---|---|---|"]
                for k, v in aug:
                    d = v["delta_ci95"]
                    lines.append(f"| {k.replace('augmented_', '')} | {f(v['base']['spearman'])} | {f(v['augmented_GM_with_S']['spearman'])} | {f(v['delta_spearman'])} | "
                                 f"{'—' if not d else f'[{d[0]:.2f}, {d[1]:.2f}]'} |")
            lines.append("")
    (e42.RESULTS / "RESULTS_semantic_screen.md").write_text("\n".join(lines) + "\n")
    print(f"wrote results/RESULTS_semantic_screen.md ({len(units)} configurations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
